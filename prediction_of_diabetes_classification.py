#import libraries
import pandas as pd
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from xgboost import XGBClassifier
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler #for feature scaling
from imblearn.over_sampling import SMOTE #using smote technique for class imbalance
from sklearn.metrics import confusion_matrix, accuracy_score, precision_score, recall_score, r2_score,f1_score
import joblib


#collect data and import dataset
df = pd.read_csv('diabetes.csv')
print(df.head())

#basic EDA
print(df.shape)

#checking for null values and column datatypes
print(df.info())

#checking for null values
print(df.isnull().sum())

#Replace 0 with NaN in specific columns
cols_with_missing = ['Glucose','BloodPressure','SkinThickness','Insulin','BMI']
df[cols_with_missing] = df[cols_with_missing].replace(0, np.nan)

#check howmany missing values
print(df.isnull().sum())

for col in cols_with_missing:
  df[col].fillna(df[col].median(), inplace =True)

print(df.isnull().sum())

plt.figure(figsize=(12,6))
sns.boxplot(data = df[cols_with_missing])
plt.title("Boxplot of features for detection of outliers")
plt.show()

def remove_outliers_iqr(df, column):
  Q1 = df[column].quantile(0.25)
  Q3 = df[column].quantile(0.75)
  IQR = Q3-Q1
  lower_bound = Q1 - 1.5*IQR
  upper_bound = Q3 + 1.5*IQR
  return df[(df[column] >= lower_bound) & (df[column] <= upper_bound)]

for col in cols_with_missing:
  df = remove_outliers_iqr(df,col)

print('Remaining dataset shape:',df.shape)

plt.figure(figsize = (10,6))
sns.boxplot(data = df[cols_with_missing])
plt.title('After Removing Outliers')
plt.show()

#checking for duplicating values
print(df.duplicated().sum())

#Distribution of Outcome
dist_outcome = df['Outcome'].value_counts()
print(type(dist_outcome))
print(dist_outcome)

plt.figure(figsize=(8,6))
plt.bar(dist_outcome.index, dist_outcome.values)
plt.xticks([0,1])
plt.show()

#diabetes based on age
diabetes_age = df.groupby('Age')['Outcome'].sum()  #series
diabetes_age.sort_values(ascending = False)

diabetes_age.plot(kind = 'bar',figsize = (10,6), color = 'skyblue')
plt.title("Diabetes Cases by Age")
plt.xlabel("Age")
plt.ylabel("Number of Diabetes Cases")
plt.show()

diabetes_bmi = df.groupby('BMI')['Outcome'].sum()
diabetes_bmi.sort_values(ascending = False)

plt.bar(diabetes_bmi.index,diabetes_bmi.values)
plt.title("Diabetes Cases by BMI")
plt.xlabel("BMI")
plt.ylabel("Number of Diabetes Cases")
plt.show()

corr = df.corr()
print(corr)

plt.figure(figsize=(10,8))
sns.heatmap(corr[['Outcome']].sort_values(by= 'Outcome' ,ascending=False), annot=True, cmap = 'coolwarm', fmt= '.2f')
plt.show()

#Feature Scaling
#Data preprocessing step
scaler = StandardScaler()
scaled_cols = ['Glucose','BloodPressure','SkinThickness','Insulin','BMI','DiabetesPedigreeFunction','Age']
df[scaled_cols] = scaler.fit_transform(df[scaled_cols])
print(df.head())

#Data preprocessing step
#splitting dataset into features and target
X = df.drop('Outcome',axis = 1)
y = df['Outcome']

#splitting into training and testing datasets
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size = 0.3,random_state = 42,stratify = y)

#There is class imbalance
#not much but there is
#we are using smote technique for class imbalance
#SMOTE (Synthetic Minority Oversampling Technique)
#Generates synthetic samples for minority class.

smote = SMOTE(random_state = 42)
X_train_smote, y_train_smote = smote.fit_resample(X_train, y_train)

print('Before SMOTE:\n',y_train.value_counts())
print('After SMOTE:\n', y_train_smote.value_counts())

#Model selection and model training
#It is a binary classification problem
#here the output is discrete
model = LogisticRegression()#object/instance of logistic regression class
model.fit(X_train_smote, y_train_smote)

print('Intercept:',model.intercept_)
print('coefficients:\n',model.coef_)

#Make predictions
y_pred = model.predict(X_test)

print('Predicted output:\n',y_pred)
print('Actual Output:\n',y_test.values)

#model evaluation
print('Confusion Matrix:\n',confusion_matrix(y_test, y_pred))
print('Accuracy:',accuracy_score(y_test, y_pred))
print('Precision:',precision_score(y_test, y_pred))
print('Recall:',recall_score(y_test, y_pred))
print('F1 Score:',f1_score(y_test, y_pred))

#using decisiontreeclassifier
model_dt = DecisionTreeClassifier(criterion='entropy',max_depth=3,random_state=42)
model_dt.fit(X_train_smote,y_train_smote)
y_pred_dt = model_dt.predict(X_test)

#Evaluation
print('Confusion Matrix:\n',confusion_matrix(y_test, y_pred_dt))
print('Accuracy:',accuracy_score(y_test, y_pred_dt))
print('Precision:',precision_score(y_test, y_pred_dt))
print('Recall:',recall_score(y_test, y_pred_dt))
print('F1 Score:',f1_score(y_test, y_pred_dt))

#using XGBoost
model_xgb = XGBClassifier( objective='binary:logistic',
    n_estimators=100,
    learning_rate=0.1,
    max_depth=6,
    random_state=42)
model_xgb.fit(X_train_smote,y_train_smote)

#prediction
y_pred_xgb = model_xgb.predict(X_test)

#Evaluation
print('Confusion Matrix:\n',confusion_matrix(y_test, y_pred_xgb))
print('Accuracy:',accuracy_score(y_test, y_pred_xgb))
print('Precision:',precision_score(y_test, y_pred_xgb))
print('Recall:',recall_score(y_test, y_pred_xgb))
print('F1 Score:',f1_score(y_test, y_pred_xgb))


joblib.dump(model_xgb,"diabetes_model.pkl")
joblib.dump(scaler,"scaler.pkl")